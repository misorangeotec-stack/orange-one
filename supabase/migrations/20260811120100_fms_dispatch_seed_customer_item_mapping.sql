-- Customers. No company is set: the customer-company mapping was retired, so a
-- customer is just a name here.
insert into public.fms_dispatch_customers (name)
select distinct c.party from _ci c
 where not exists (select 1 from public.fms_dispatch_customers x where upper(x.name) = upper(c.party));

insert into public.fms_dispatch_items (name)
select distinct c.item from _ci c
 where not exists (select 1 from public.fms_dispatch_items x where upper(x.name) = upper(c.item));

insert into public.fms_dispatch_customer_items (customer_id, item_id)
select cu.id, it.id
  from _ci c
  join public.fms_dispatch_customers cu on upper(cu.name) = upper(c.party)
  join public.fms_dispatch_items     it on upper(it.name) = upper(c.item)
on conflict (customer_id, item_id) do nothing;

